-- FlyIM 社区版空库安装结构。仅包含社区版实际依赖的基础表。
-- 目标为空白 MySQL 数据库；执行前确认数据库中没有现有表。

CREATE TABLE `app_account_deletion_request`  (
  `deletion_request_id` varchar(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '对外账号注销申请ID',
  `user_id` bigint UNSIGNED NOT NULL COMMENT '申请注销的用户ID',
  `status` tinyint UNSIGNED NOT NULL DEFAULT 10 COMMENT '注销状态：10冷静期中 20已取消 30已生效',
  `pending_user_id` bigint UNSIGNED GENERATED ALWAYS AS (if((`status` = 10),`user_id`,NULL)) STORED COMMENT '仅冷静期记录参与唯一约束的用户ID' NULL,
  `requested_at` int UNSIGNED NOT NULL COMMENT '申请时间，Unix秒',
  `effective_at` int UNSIGNED NOT NULL COMMENT '计划生效时间，Unix秒',
  `cancelled_at` int UNSIGNED NULL DEFAULT NULL COMMENT '取消时间，Unix秒',
  `create_time` int UNSIGNED NOT NULL COMMENT '创建时间，Unix秒',
  `update_time` int UNSIGNED NOT NULL COMMENT '更新时间，Unix秒',
  PRIMARY KEY (`deletion_request_id`) USING BTREE,
  UNIQUE INDEX `uniq_deletion_pending_user`(`pending_user_id` ASC) USING BTREE,
  INDEX `idx_deletion_effective`(`status` ASC, `effective_at` ASC) USING BTREE,
  INDEX `fk_deletion_user`(`user_id` ASC) USING BTREE,
  CONSTRAINT `fk_deletion_user` FOREIGN KEY (`user_id`) REFERENCES `app_user` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `chk_deletion_status` CHECK (`status` in (10,20,30))
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = '账号注销冷静期申请' ROW_FORMAT = DYNAMIC;

CREATE TABLE `app_auth_audit`  (
  `audit_id` bigint UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '认证安全审计主键ID',
  `request_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'API请求ID',
  `event` varchar(64) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT '安全事件：register login_password token_refresh logout password_change account_delete等',
  `result` tinyint UNSIGNED NOT NULL COMMENT '审计结果：10成功 20失败 30拒绝',
  `user_id` bigint UNSIGNED NULL DEFAULT NULL COMMENT '已识别的用户ID',
  `identity_type` tinyint UNSIGNED NULL DEFAULT NULL COMMENT '登录标识类型：10手机号 20邮箱 30用户名',
  `identity_hash` binary(32) NULL DEFAULT NULL COMMENT '登录标识规范值的HMAC-SHA256',
  `session_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '相关会话UUID v4',
  `device_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '相关设备UUID v4',
  `ip` varchar(45) CHARACTER SET ascii COLLATE ascii_general_ci NULL DEFAULT NULL COMMENT '请求IP，支持IPv4和IPv6',
  `user_agent` varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NULL DEFAULT NULL COMMENT '请求User-Agent',
  `reason_code` varchar(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL DEFAULT NULL COMMENT '稳定失败原因代码',
  `context` json NULL COMMENT '不含敏感值的低频扩展信息',
  `create_time` int UNSIGNED NOT NULL COMMENT '创建时间，Unix秒',
  PRIMARY KEY (`audit_id`) USING BTREE,
  INDEX `idx_auth_audit_request`(`request_id` ASC) USING BTREE,
  INDEX `idx_auth_audit_event_time`(`event` ASC, `create_time` DESC) USING BTREE,
  INDEX `idx_auth_audit_user_time`(`user_id` ASC, `create_time` DESC) USING BTREE,
  INDEX `idx_auth_audit_identity_time`(`identity_hash` ASC, `create_time` DESC) USING BTREE,
  INDEX `idx_auth_audit_session`(`session_id` ASC) USING BTREE,
  INDEX `idx_auth_audit_ip_time`(`ip` ASC, `create_time` DESC) USING BTREE,
  INDEX `idx_dashboard_auth_result_time`(`result` ASC, `create_time` ASC) USING BTREE,
  CONSTRAINT `chk_auth_audit_identity_type` CHECK ((`identity_type` is null) or (`identity_type` in (10,20,30))),
  CONSTRAINT `chk_auth_audit_result` CHECK (`result` in (10,20,30))
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = '认证与账号安全审计' ROW_FORMAT = DYNAMIC;

