  `cleared_before_seq` bigint UNSIGNED NOT NULL DEFAULT 0 COMMENT '用户清空聊天记录到此序号',
  `unread_count` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '用户当前未读数，可由last_read_seq重算',
  `is_pinned` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '是否置顶：0否 1是',
  `is_muted` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '是否免打扰：0否 1是',
  `is_hidden` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '是否在会话列表隐藏：0否 1是',
  `last_event_id` bigint UNSIGNED NOT NULL DEFAULT 0 COMMENT '该用户在此会话最后可见事件ID，阶段1暂保留为0',
