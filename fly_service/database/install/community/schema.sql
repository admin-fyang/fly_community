  `user_id` bigint UNSIGNED NOT NULL COMMENT '用户ID',
  `member_role` tinyint UNSIGNED NOT NULL DEFAULT 10 COMMENT '会话成员角色：10普通成员 20管理员 30群主',
  `join_seq` bigint UNSIGNED NOT NULL DEFAULT 0 COMMENT '用户加入会话时的消息序号，小于该序号的消息默认不可见',
