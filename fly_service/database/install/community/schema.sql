  INDEX `idx_member_user_conversation`(`user_id` ASC, `conversation_id` ASC) USING BTREE,
  CONSTRAINT `fk_conversation_member_conversation` FOREIGN KEY (`conversation_id`) REFERENCES `app_conversation` (`conversation_id`) ON DELETE CASCADE ON UPDATE RESTRICT,
  CONSTRAINT `fk_conversation_member_user` FOREIGN KEY (`user_id`) REFERENCES `app_user` (`user_id`) ON DELETE CASCADE ON UPDATE RESTRICT,
  CONSTRAINT `chk_conversation_member_flags` CHECK ((`is_pinned` in (0,1)) and (`is_muted` in (0,1)) and (`is_hidden` in (0,1))),
  CONSTRAINT `chk_conversation_member_role` CHECK (`member_role` = 10)
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_unicode_ci COMMENT = 'IM会话成员状态表' ROW_FORMAT = DYNAMIC;

